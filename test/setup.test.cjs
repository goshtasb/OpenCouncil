const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const { spawnSync } = require('child_process');
const { lib, home, makeRepo, setup, PLAN, OBJECT, SHIP, SIGNOFF, LEAD_OK, engines, revision, ScriptedAdapter } = require('./helpers.cjs');

const bin = path.join(__dirname, '..', 'bin', 'council.js');
const run = (cwd, ...args) => spawnSync(process.execPath, [bin, ...args], { cwd, env: { ...process.env, COUNCIL_HOME: home }, encoding: 'utf8' });
const template = fs.readFileSync(path.join(__dirname, '..', 'templates', '.council', 'config.yml'), 'utf8');

test('planSeats: only Claude Code installed → solo mode, every seat on claude-code with distinct models', () => {
  const plan = lib.planSeats(new Set(['claude-code']));
  assert.equal(plan.mode, 'solo');
  assert.deepEqual(plan.seats, {
    lead_pm: { provider: 'claude-code', model: 'sonnet' },
    chief_engineer: { provider: 'claude-code', model: 'opus' },
    chief_architect: { provider: 'claude-code', model: 'sonnet' }
  });
  assert.match(plan.notes.join(' '), /Only Claude Code was found/);
});

test('planSeats: all three CLIs → the default full council; partial installs fill the gaps with Claude Code', () => {
  assert.equal(lib.planSeats(new Set(['claude-code', 'antigravity', 'grok-cli'])).mode, 'full');
  const noGrok = lib.planSeats(new Set(['claude-code', 'antigravity']));
  assert.equal(noGrok.mode, 'mixed');
  assert.equal(noGrok.seats.lead_pm.provider, 'antigravity');
  assert.equal(noGrok.seats.chief_architect.provider, 'claude-code', 'Antigravity never holds the zero-tool seat');
  const noGemini = lib.planSeats(new Set(['claude-code', 'grok-cli']));
  assert.equal(noGemini.seats.lead_pm.provider, 'claude-code');
  assert.equal(noGemini.seats.chief_architect.provider, 'grok-cli');
  const nothing = lib.planSeats(new Set());
  assert.equal(nothing.mode, 'none');
  assert.equal(nothing.seats.chief_engineer.provider, 'claude-code');
  const noClaude = lib.planSeats(new Set(['grok-cli']));
  assert.equal(noClaude.seats.chief_engineer.provider, 'grok-cli');
  assert.match(noClaude.notes.join(' '), /only been verified on Claude Code/);
});

test('renderConfig: rewrites only the seat lines and profile of the shipped template, and stays valid YAML', () => {
  const plan = lib.planSeats(new Set(['claude-code']));
  const rendered = lib.renderConfig(template, plan, { profile: 'full', detected: ['claude-code (claude)'] });
  const parsed = yaml.load(rendered);
  assert.equal(parsed.seats.lead_pm.provider, 'claude-code');
  assert.equal(parsed.seats.lead_pm.model, 'sonnet');
  assert.equal(parsed.seats.chief_engineer.model, 'opus');
  assert.equal(parsed.seats.chief_architect.provider, 'claude-code');
  assert.equal(parsed.council.profile, 'full');
  assert.equal(parsed.council.max_rounds, 10, 'full profile keeps the template budget');
  assert.match(rendered, /^# Generated by `council init` \(solo mode\)/);
  assert.match(rendered, /`agy models` lists valid ids/, 'template comments survive');
  assert.deepEqual(yaml.load(rendered).verification, yaml.load(template).verification);

  const quick = yaml.load(lib.renderConfig(template, plan, { profile: 'quick' }));
  assert.equal(quick.council.profile, 'quick');
  assert.equal(quick.council.max_rounds, 4);
  assert.equal(quick.council.tiebreak_round, 3);
  assert.equal(quick.council.signoff_revisions, 1);
});

test('CLI: init --solo --quick writes a loadable solo config; --force rewrites only config.yml', () => {
  const repo = makeRepo();
  const r = run(repo, 'init', '--solo', '--quick');
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /solo mode, quick profile/);
  const config = lib.loadConfig(repo);
  assert.equal(config.seats.lead_pm.provider, 'claude-code');
  assert.equal(config.seats.chief_architect.model, 'sonnet');
  assert.equal(config.council.profile, 'quick');
  assert.equal(config.council.max_rounds, 4);

  fs.writeFileSync(path.join(repo, '.council', 'personas', 'lead-pm.md'), '# custom persona\n');
  assert.match(run(repo, 'init').stdout, /already exists/);
  const forced = run(repo, 'init', '--full', '--force');
  assert.equal(forced.status, 0, forced.stderr);
  assert.equal(lib.loadConfig(repo).seats.chief_architect.provider, 'grok-cli');
  assert.equal(fs.readFileSync(path.join(repo, '.council', 'personas', 'lead-pm.md'), 'utf8'), '# custom persona\n', 'customized files are kept');
});

